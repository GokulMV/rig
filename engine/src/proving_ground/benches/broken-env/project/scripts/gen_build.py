"""Writes src/inventory/_build.py from VERSION. Run it after changing VERSION."""

from pathlib import Path

root = Path(__file__).resolve().parent.parent
version = (root / "VERSION").read_text().strip()
(root / "src" / "inventory" / "_build.py").write_text(
    f'# Generated by scripts/gen_build.py from VERSION. Do not edit.\nVERSION = "{version}"\n'
)
