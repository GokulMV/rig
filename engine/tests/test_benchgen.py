import re
import subprocess
import sys
from pathlib import Path

from proving_ground import benchgen
from proving_ground.generate.client import ToolCall

CHECK_OK = """
from pathlib import Path
assert Path("/app/out.txt").read_text().strip() == "42", "out.txt must say 42"
"""
SPEC = {
    "name": "Answer bench",
    "summary": "Write the answer.",
    "files": [{"path": "README.md", "content": "Write 42 to out.txt."}],
    "tasks": [
        # Proven both ways: kept.
        {
            "id": "answer",
            "title": "Answer",
            "kind": "edge",
            "step": "Implement",
            "instruction": "Write 42 to out.txt.",
            "check": CHECK_OK,
            "solution": [{"path": "out.txt", "content": "42\n"}],
            "wrong_solution": [{"path": "out.txt", "content": "24\n"}],
        },
        # Only checks the file exists, so it accepts a wrong answer: dropped.
        {
            "id": "shape",
            "title": "Shape",
            "kind": "typical",
            "step": "x",
            "instruction": "Write 42.",
            "check": "from pathlib import Path\nassert Path('/app/out.txt').exists()\n",
            "solution": [{"path": "out.txt", "content": "42\n"}],
            "wrong_solution": [{"path": "out.txt", "content": "7\n"}],
        },
        # Passes untouched: dropped.
        {
            "id": "trivial",
            "title": "Trivial",
            "kind": "typical",
            "step": "x",
            "instruction": "Nothing.",
            "check": "pass\n",
            "solution": [],
        },
        # Fails on its own solution: dropped.
        {
            "id": "wrong",
            "title": "Wrong",
            "kind": "typical",
            "step": "x",
            "instruction": "Write 42.",
            "check": CHECK_OK,
            "solution": [{"path": "out.txt", "content": "41\n"}],
        },
        # Tries to write outside the project: dropped.
        {
            "id": "escape",
            "title": "Escape",
            "kind": "adversarial",
            "step": "x",
            "instruction": "x",
            "check": CHECK_OK,
            "solution": [{"path": "../../etc/x", "content": "42"}],
        },
    ],
}


class Model:
    def __init__(self):
        self.calls = []

    def call(self, prompt, tool, model, max_tokens):
        self.calls.append(prompt)
        return ToolCall(SPEC, "tool_use", 0, 0)


def fake_docker(cmd, **kw):
    """Stand-in for `docker run`: run the check here, with the mounts mapped to the real folders."""
    assert cmd[:4] == ["docker", "run", "--rm", "--network"] and cmd[4] == "none"
    vols = [cmd[i + 1].split(":") for i, a in enumerate(cmd) if a == "-v"]
    mounts = {v[1]: v[0] for v in vols}  # container path -> host folder
    script = Path(mounts["/tests/checks"]) / cmd[-1].removeprefix("/tests/checks/")
    text = script.read_text().replace("/app", mounts["/app"])
    return subprocess.run([sys.executable, "-c", text], capture_output=True, text=True)


def test_only_tasks_proven_three_ways_are_kept(tmp_path: Path):
    m = Model()
    wf = {
        "id": "w1",
        "name": "Answer things",
        "discipline": "qa",
        "steps": [{"name": "Implement", "kind": "do", "does": "Write it."}],
    }
    made = benchgen.make(m, wf, tmp_path / "generated", "test-model", run=fake_docker)
    assert made.kept == ["answer"]
    assert set(made.dropped) == {"trivial", "wrong", "escape", "shape"}
    assert made.dropped["shape"] == "the check accepts a wrong answer"
    assert "passes on the untouched" in made.dropped["trivial"]
    assert "fails on the reference solution" in made.dropped["wrong"]
    assert "unsafe path" in made.dropped["escape"]
    assert "Implement (do)" in m.calls[0].content[0]["text"]
    root = tmp_path / "generated" / made.bench_id
    assert (root / "checks" / "answer" / "check.py").is_file() and not (
        root / "checks" / "wrong"
    ).exists()
    assert not list((tmp_path / "generated").glob(".work-*"))  # the scratch work is gone

    from proving_ground import bench as bench_mod

    bench_mod.GENERATED = tmp_path / "generated"
    try:
        b = bench_mod.bench(made.bench_id)
        assert b.generated == {"by": "test-model", "workflow": "w1"} and b.disciplines == ["qa"]
        assert [s["title"] for s in b.scenarios] == ["Answer (for Implement)"]
        assert re.search(r"Generated by test-model", b.summary)
        p = bench_mod.materialize(b, tmp_path / "p")
        assert (p / "README.md").is_file() and (
            p / ".proving-ground" / "checks" / "answer"
        ).is_dir()
    finally:
        bench_mod.GENERATED = None


def test_the_proofs_run_in_docker_with_no_network(tmp_path: Path):
    seen = []

    def spy(cmd, **kw):
        seen.append(cmd)
        return fake_docker(cmd, **kw)

    benchgen.make(Model(), {"id": "w", "name": "n", "steps": []}, tmp_path / "g", "m", run=spy)
    assert seen and all(c[:5] == ["docker", "run", "--rm", "--network", "none"] for c in seen)
    assert all(any(a.endswith(":/tests/checks:ro") for a in c) for c in seen)


def test_checks_can_import_the_project(tmp_path: Path):
    """A generated check that imports a project module works: /app is put on its path."""
    spec = {
        "name": "n",
        "summary": "s",
        "files": [{"path": "calc.py", "content": "def add(a, b):\n    return a - b\n"}],
        "tasks": [
            {
                "id": "add",
                "title": "Fix add",
                "kind": "typical",
                "step": "x",
                "instruction": "add should add.",
                "check": "from calc import add\nassert add(2, 3) == 5\n",
                "solution": [{"path": "calc.py", "content": "def add(a, b):\n    return a + b\n"}],
                "wrong_solution": [
                    {"path": "calc.py", "content": "def add(a, b):\n    return a * b\n"}
                ],
            }
        ],
    }

    class M:
        def call(self, *a):
            return ToolCall(spec, "tool_use", 0, 0)

    def docker_with_path(cmd, **kw):
        # Like fake_docker, but the check runs from its own folder as in the container, so only
        # the preamble makes /app importable.
        vols = [cmd[i + 1].split(":") for i, a in enumerate(cmd) if a == "-v"]
        mounts = {v[1]: v[0] for v in vols}
        script = Path(mounts["/tests/checks"]) / cmd[-1].removeprefix("/tests/checks/")
        text = script.read_text().replace("/app", mounts["/app"])
        return subprocess.run(
            [sys.executable, "-c", text], capture_output=True, text=True, cwd=script.parent
        )

    made = benchgen.make(
        M(), {"id": "w", "name": "n", "steps": []}, tmp_path / "g", "m", run=docker_with_path
    )
    assert made.kept == ["add"], made.dropped
